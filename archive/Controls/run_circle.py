# ---------------------------------------------------------------------------
# Flight function
# ---------------------------------------------------------------------------


def fly_circle(scf, n_laps):
    cf = scf.cf
    hl = cf.high_level_commander
    traj_id = 1

    print(f"\nUploading circle trajectory ({len(circle_poly4d)} segments)...")
    duration = upload_trajectory(cf, traj_id, circle_poly4d, scale=SCALE)
    actual_s = duration / SPEED_SCALE
    print(
        f"  Planned: {duration:.2f} s  |  at SPEED_SCALE={SPEED_SCALE}: {actual_s:.1f} s/lap"
    )
    print(f"  {n_laps} lap(s): {actual_s * n_laps:.1f} s total")

    print("Resetting Kalman estimator...")
    reset_kalman(cf)
    wait_for_kalman(scf)

    cf.platform.send_arming_request(True)
    time.sleep(1.0)

    cf.param.set_value("stabilizer.controller", "1")
    time.sleep(0.1)

    log_cfg = start_live_log(cf)
    logger = FlightLogger(cf, name="circle")
    logger.start()

    print(f"\nTakeoff to {HOVER_HEIGHT:.2f} m over 2 s...")
    hl.takeoff(HOVER_HEIGHT, 2.0)
    print("  Waiting 3 s for climb + estimator stabilization...")
    time.sleep(3.0)

    cf.param.set_value("stabilizer.controller", "6")

    print("\nOOT Rust geometric controller active. Stabilizing hover for 2.5 s...")
    time.sleep(2.5)

    for lap in range(1, n_laps + 1):
        print(f"\n--- Lap {lap}/{n_laps}: starting trajectory ---")
        print(f"  Duration: {actual_s:.1f} s at SPEED_SCALE={SPEED_SCALE}")
        if lap == 1:
            logger.mark_traj_start()
        hl.start_trajectory(traj_id, 1.0 / SPEED_SCALE, relative_position=True)
        time.sleep(max(0.5, actual_s - 0.05))

    time.sleep(1.5)
    cf.param.set_value("stabilizer.controller", "1")

    print("\nLanding...")
    logger.stop()
    log_cfg.stop()
    hl.land(0.0, 2.0)
    time.sleep(2.0)
    hl.stop()
    print("Done.")


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Circle flight via HLC")
    parser.add_argument(
        "--laps", type=int, default=DEFAULT_LAPS, help="Number of laps (default: 1)"
    )
    parser.add_argument(
        "--uri",
        default=None,
        help="Crazyflie URI (default: radio://0/80/2M/E7E7E7E7E7)",
    )
    args = parser.parse_args()

    uri = args.uri or uri_helper.uri_from_env(default=DEFAULT_URI)
    print(f"Connecting to {uri}...")
    print(f"Laps: {args.laps}  |  SPEED_SCALE: {SPEED_SCALE}")

    cflib.crtp.init_drivers()
    with SyncCrazyflie(uri, cf=Crazyflie(rw_cache="./cache")) as scf:
        fly_circle(scf, n_laps=args.laps)
