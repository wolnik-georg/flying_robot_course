#!/usr/bin/env python3
"""Emit the flash-resident NS2 weights for the C implementation (ns2_residual.c, Omar C controller tree).

Slices the three blocks the network actually uses out of the 19 297-float vector of the .npz
(layout phi_S | phi_L | phi_G | rho_S | rho_L) and writes them as const float arrays with the sha256 of the
source file. phi_L / rho_L are unused (every vehicle in this project is "small").

  python3 tools/residual/export_weights_c.py tools/residual/weights/ns2_v1.npz firmware_app/ns2_weights.c
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

import numpy as np

N_PHI_S, N_PHI_G, N_RHO = 3675, 3625, 4161
OFF_PHI_S = 0
OFF_PHI_L = OFF_PHI_S + N_PHI_S
OFF_PHI_G = OFF_PHI_L + N_PHI_S
OFF_RHO_S = OFF_PHI_G + N_PHI_G
OFF_RHO_L = OFF_RHO_S + N_RHO
N_TOTAL = OFF_RHO_L + N_RHO  # 19297


def blocks(w: np.ndarray) -> dict[str, np.ndarray]:
    return {
        "ns2_w_phi_s": w[OFF_PHI_S:OFF_PHI_S + N_PHI_S],
        "ns2_w_phi_g": w[OFF_PHI_G:OFF_PHI_G + N_PHI_G],
        "ns2_w_rho_s": w[OFF_RHO_S:OFF_RHO_S + N_RHO],
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("npz", type=Path)
    ap.add_argument("out_c", type=Path)
    a = ap.parse_args()
    w = np.load(a.npz)["weights"].astype(np.float32)
    if w.shape != (N_TOTAL,):
        print(f"expected {N_TOTAL} weights, got {w.shape}", file=sys.stderr)
        return 1
    if not np.all(np.isfinite(w)):
        print("non-finite weights in npz", file=sys.stderr)
        return 1
    sha = hashlib.sha256(a.npz.read_bytes()).hexdigest()
    out = [
        "/* @generated by tools/residual/export_weights_c.py -- do not edit */",
        f"/* source: {a.npz.name}  sha256: {sha} */",
        "#include <stdint.h>",
        "",
        f'const char ns2_weights_sha256[] = "{sha}";',
        "",
    ]
    for name, b in blocks(w).items():
        out.append(f"const float {name}[{len(b)}] = {{")
        for i in range(0, len(b), 6):
            out.append("  " + ", ".join(f"{float(x):.9e}f" for x in b[i:i + 6]) + ",")
        out.append("};")
        out.append("")
    a.out_c.write_text("\n".join(out))
    print(f"wrote {a.out_c}: {sum(len(b) for b in blocks(w).values())} floats, sha256 {sha[:12]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
