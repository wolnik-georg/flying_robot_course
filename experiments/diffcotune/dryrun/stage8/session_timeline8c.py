#!/usr/bin/env python3
"""Stage 8c T6: session-1 timeline (S0 + S2) with 6 rounds x 5 tuning flights (A1, A8, A4 cell 1 two-drone, --solo relaunch, CIRCLE, FIG8) + 12 test flights and the Stage 8b desk minutes of results/loop_<C>_ours.json.
Uses the schedule model of lab/session_timeline.py (not edited; sequential / interleaved functions copied here with 3 + 2 flights per round). Writes lab/results/session_timeline.md and .json (old ones kept as session_timeline.before_stage8c.*).
Desk minutes: round l = seconds_round of round l of loop_<C>_ours.json; the last round (5) has no desk step = 0.1 min (convention of the old file). A controller with fewer than 6 flown rounds in the file: NOT computed ("not yet").
'Two at once' desk times for "ours" were NOT measured: case A = the same as alone; case B = x1.28 (S0) / x1.18 (S2), the factors measured on 15 Nov for the OLD variant (round-0 test), applied to rounds 0-4: a sensitivity, not a measurement.
Usage: nice -n 19 /usr/bin/python3 session_timeline8c.py"""
import json, sys
from pathlib import Path
H = Path(__file__).resolve().parent; LAB = H.parents[1] / 'lab'; sys.path.insert(0, str(LAB))
import session_timeline as ST
FLY = ST.FLY_S; N_ROUNDS = 6; N_TEST = 12; BEFORE, AFTER = 3, 2


def desk(C):
    r = json.load(open(H / 'results' / ('loop_%s_ours.json' % C)))['rounds']
    return [x['seconds_round'] / 60 for x in r[:5]] + [0.1] if len(r) >= 6 else None


def sequential(ctrls, d, sw, solo):
    t = 0.0; seg = []
    def add(x, k, c):
        nonlocal t; seg.append((t, t + x, k, c)); t += x
    for c in ctrls:
        add(sw, 'switch', c); td = N_TEST // 2
        for l in range(N_ROUNDS):
            add(BEFORE * FLY / 60, 'fly', c); add(solo, 'solo relaunch', c); add(AFTER * FLY / 60, 'fly', c); w = d[c][l]
            if l == 0 and td:
                x = min(w, td * FLY / 60); add(x, 'test', c); w -= x
            if w > 0: add(w, 'idle', c)
        add(N_TEST // 2 * FLY / 60, 'test', c)
    return seg


def interleaved(pair, d, sw, solo):
    A, B = pair; t = 0.0; seg = []; nxt = {A: 0, B: 0}; ready = {A: 0.0, B: 0.0}; loaded = None; tl = {A: N_TEST // 2, B: N_TEST // 2}; bt = N_TEST // 2
    def add(x, k, c):
        nonlocal t; seg.append((t, t + x, k, c)); t += x
    order = [A, B]; i = 0
    while nxt[A] < N_ROUNDS or nxt[B] < N_ROUNDS:
        c = order[i % 2]; i += 1
        if nxt[c] >= N_ROUNDS: continue
        if loaded != c: add(sw, 'switch', c); loaded = c
        while ready[c] > t and tl[c] > 0 and (ready[c] - t) >= FLY / 60: add(FLY / 60, 'test', c); tl[c] -= 1
        if ready[c] > t: add(ready[c] - t, 'idle', c)
        l = nxt[c]; add(BEFORE * FLY / 60, 'fly', c); add(solo, 'solo relaunch', c); add(AFTER * FLY / 60, 'fly', c); ready[c] = t + d[c][l]; nxt[c] += 1
    for c in sorted((A, B), key=lambda x: ready[x]):
        if loaded != c: add(sw, 'switch', c); loaded = c
        while tl[c] > 0 and ready[c] > t: add(FLY / 60, 'test', c); tl[c] -= 1
        if ready[c] > t: add(ready[c] - t, 'idle', c)
        for _ in range(tl[c] + bt): add(FLY / 60, 'test', c)
        tl[c] = 0
    return seg


def main():
    pair = ('S0', 'S2'); ds = {}
    for C in pair:
        try: ds[C] = desk(C)
        except Exception: ds[C] = None
    if any(v is None for v in ds.values()):
        print('not yet: fewer than 6 flown rounds in loop_<C>_ours.json for', [c for c in pair if ds[c] is None]); return 1
    cases = {'A (two at once = alone)': ds, 'B (two at once = alone x1.28 S0 / x1.18 S2, rounds 0-4)': {'S0': [x * 1.28 for x in ds['S0'][:5]] + [0.1], 'S2': [x * 1.18 for x in ds['S2'][:5]] + [0.1]}}
    rows = ['| overhead (switch and --solo relaunch) | mode | desk case | hours | flying min | idle min | switch + relaunch min | flights | flights per hour |', '|---|---|---|---|---|---|---|---|---|']; out = {}
    for ov in (3, 5, 10):
        sq = ST.summarise(sequential(pair, ds, ov, ov)); rows.append('| %d min | sequential | alone | %.2f | %.0f | %.0f | %.0f | %d | %.1f |' % (ov, sq['hours'], sq['flying_min'], sq['idle_min'], sq['switch_min'], sq['flights'], sq['flights_per_hour']))
        out[str(ov)] = dict(sequential=sq)
        for nm, dd in cases.items():
            it = ST.summarise(interleaved(pair, dd, ov, ov)); rows.append('| %d min | interleaved | %s | %.2f | %.0f | %.0f | %.0f | %d | %.1f |' % (ov, nm, it['hours'], it['flying_min'], it['idle_min'], it['switch_min'], it['flights'], it['flights_per_hour'])); out[str(ov)]['interleaved ' + nm] = it
    md = ['# Session 1 (S0 + S2) timeline, Stage 8c (model, not a measurement; generated by `dryrun/stage8/session_timeline8c.py`)', '',
          'Parameters: %.1f s per flight (mean spacing of the S0 block of 23 Oct, from `lab/session_timeline.py`), per round %d flights (A1, A8, A4 cell 1), `--solo` relaunch, %d flights (CIRCLE, FIG8) = 5 tuning flights, %d rounds (0–5), %d test flights per controller (6 default gains, 6 θ_best).' % (FLY, BEFORE, AFTER, N_ROUNDS, N_TEST), '',
          'Desk minutes per round (round 0 … 5, `seconds_round` of `results/loop_<C>_ours.json`; round 5 = 0.1): ' + '; '.join('%s: %s' % (c, ' / '.join('%.0f' % x for x in ds[c][:5]) + ' / 0.1') for c in pair) + '. Two-at-once desk times for "ours": not measured (cases A and B above, B is a sensitivity with the factors measured for the old variant).', '',
          'Sequential uses the alone desk times; the desk PC runs out of memory with two "ours" pools at once (15 Nov incident): case A / B assume the lab PC can run both loops at once, which is not stated.', ''] + rows + ['', 'Not stated (not in the repository, not measured): the switch overhead (3 / 5 / 10 min is a parameter), the extra --solo relaunch time (same parameter), flights per battery pack, packs per hour, which PC runs the loops in the lab, uSD handling time.']
    (LAB / 'results' / 'session_timeline.md').write_text('\n'.join(md) + '\n'); json.dump(dict(desk=ds, results=out, params=dict(fly_s=FLY, rounds=N_ROUNDS, test=N_TEST, before=BEFORE, after=AFTER)), open(LAB / 'results' / 'session_timeline.json', 'w'), indent=1); print('\n'.join(md))
    return 0


if __name__ == '__main__':
    sys.exit(main())
