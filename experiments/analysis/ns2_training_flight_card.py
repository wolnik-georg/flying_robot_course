#!/usr/bin/env python3
"""NS2 training-data flight card (Topic 2, docs/plan_ns2_retrain_data_2026-10-14.md): dedicated flights on the Omar C tree
with strategy S0 (indi 0, NS2 off), separate from the study repeats. Every command is validated with the scenario generator
and the geofence check as flown (--auto-center, height 0.5).
  python3 experiments/analysis/ns2_training_flight_card.py   ->  docs/ns2_training_flight_card.md"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from study_flight_plan import setting, validate, cli, A8_DURATION, A2_PERIOD  # noqa: E402

REPO = HERE.parents[1]
rows = []


def add(block, s, reps=1):
    s = validate(s)
    for _ in range(reps):
        rows.append((block, s))


for dz in (0.25, 0.375, 0.5, 0.625, 0.75):
    add("A1 stack hold", setting("A1", "dz", dz), 2)
for off in (0.0, 0.05, 0.10, 0.15):
    for dz in (0.25, 0.5, 0.75):
        s = setting("A4", "speed", 0.4); s["kwargs"].update(dz=dz, offset=off); s["setting"] = f"dz={dz} offset={off} speed=0.4"
        add("A4 offset stack", s)
for sp in (0.2, 0.3, 0.4, 0.5):
    add("A8 swap", setting("A8", "speed", sp), 2)
    for sc in ("A2", "A3", "A5", "A7"):
        add(f"{sc}", setting(sc, "speed", sp))
for seed in range(101, 121):
    s = {"scenario": "R1", "setting": f"seed={seed}", "kwargs": dict(seed=seed, total=40.0, bias=0.7)}
    add("R1 random waypoints", s)

L = ["# NS2 training-data flight card (generated by `experiments/analysis/ns2_training_flight_card.py`)", "",
     f"{len(rows)} flights, all with the study tree strategy S0 (`tree_S0.patch`: Omar geometric on both drones, NS2 off, deck RPM on), "
     "dedicated training data, NOT study repeats. **Flown WITHOUT `--study`** (the readback gate returned NaN on 2026-10-15; the training data does not need it): the strategy is read from the log (`experiments/analysis/tree_log_check.py`) and the file is tagged `ns2_train` at copy time.  Prerequisite: lab validation of the tree (`docs/lab_sessions/next_session_plan.md`). "
     "Labels are reconstructed offline (`docs/plan_ns2_retrain_data_2026-10-14.md` §1). Abort rule protocol §4; fresh batteries; one uSD file per flight.", "",
     "| # | block | scenario | setting | duration (s) | command | done | notes |", "|---|---|---|---|---:|---|---|---|"]
bad = 0
for i, (blk, s) in enumerate(rows, 1):
    if s["scenario"] == "R1":
        from crazyflie_examples.formations import scenarios, safety
        from crazyflie_examples.run_formation import centred_anchor
        sc = scenarios.build("R1", **s["kwargs"])
        lim = safety.Limits(); base = centred_anchor(sc, lim, 0.5)
        prob = safety.check(sc, lim, base=base)
        s = dict(s, valid=not prob, allow_extreme=False, duration_s=sc.duration, kwargs=dict(s["kwargs"]))
        s["kwargs"] = {"seed": s["kwargs"]["seed"], "total": s["kwargs"]["total"], "bias": s["kwargs"]["bias"]}
    if not s.get("valid", True):
        bad += 1
    L.append(f"| {i} | {blk} | {s['scenario']} | {s['setting']} | {s['duration_s']:.0f} | `{cli(s, 'S0', 'ns2_train').replace(' --study --strategy S0 --session ns2_train', '')}` | ☐ | {'' if s.get('valid', True) else 'INVALID'} |")
tot = sum(s["duration_s"] for _, s in rows)
L += ["", f"Total flight time ≈ {tot / 60:.0f} min (+ takeoff/landing and battery changes); ≈ {len(rows) / 12:.1f} h at 12 flights/hour."]
(REPO / "docs" / "ns2_training_flight_card.md").write_text("\n".join(L) + "\n")
print(f"{len(rows)} flights, invalid {bad}, flight time {tot / 60:.0f} min")
sys.exit(1 if bad else 0)
