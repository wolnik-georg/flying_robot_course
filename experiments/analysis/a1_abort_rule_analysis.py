#!/usr/bin/env python3
"""Abort-rule analysis (2026-10-11): how to tell the A1 downwash oscillation (+-35 deg, ~1.5 Hz, recovers) from a tumble.
Combined tilt = arccos(cos(roll) cos(pitch)) from the logged stabilizer angles of every cf5 uSD flight; per flight the longest
continuous time above a threshold (airborne samples only). Writes out/abort_rule/{table.csv,fig_abort_rule.png} and docs/a1_abort_rule_analysis.md."""
import csv, glob, sys
from pathlib import Path
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO / "flying_drone_stack" / "tools"))
import decode_usd_log as dec  # noqa: E402

OUT = HERE / "out" / "abort_rule"; OUT.mkdir(parents=True, exist_ok=True)
THRESH = (25, 35, 45, 50, 60)


def longest(mask, dt):
    best = cur = 0.0
    for v in mask:
        cur = cur + dt if v else 0.0
        best = max(best, cur)
    return best


def main():
    rows = []
    for f in sorted(glob.glob(str(REPO / "experiments/logs/usd_raw/cf5_*.bin"))):
        try:
            r = dec.load(f)
        except Exception:
            continue
        t = np.asarray(r["t"]); 
        if len(t) < 2000:
            continue
        up = np.asarray(r["z"]) > 0.1
        if not up.any():
            continue
        roll, pitch = np.radians(r["roll_deg"]), np.radians(r["pitch_deg"])
        tilt = np.degrees(np.arccos(np.clip(np.cos(roll) * np.cos(pitch), -1, 1)))
        dt = float(np.median(np.diff(t)))
        name = Path(f).name
        row = {"file": name, "max_tilt_deg": float(tilt[up].max())}
        for th in THRESH:
            row[f"longest_above_{th}_s"] = longest((tilt > th) & up, dt)
        # time from first > 50 deg to first > 90 deg (how long a human has) -- only for tumbles
        i50 = np.argmax((tilt > 50) & up) if ((tilt > 50) & up).any() else None
        i90 = np.argmax((tilt > 90) & up) if ((tilt > 90) & up).any() else None
        row["t_50_to_90_s"] = float(t[i90] - t[i50]) if (i50 is not None and i90 is not None) else float("nan")
        row["class"] = "tumble (>90 deg)" if row["max_tilt_deg"] > 90 else ("ambiguous 50-90 deg" if row["max_tilt_deg"] > 50 else "no tumble (<=50 deg)")
        rows.append(row)
    with open(OUT / "table.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)

    # candidate rules
    def n_trig(cls, th, dur):
        sub = [x for x in rows if x["class"].startswith(cls)]
        return sum(1 for x in sub if x[f"longest_above_{th}_s"] >= dur), len(sub)
    rules = [(25, 0.5), (35, 0.5), (35, 0.2), (45, 0.2), (45, 0.1), (50, 0.2), (50, 0.1), (60, 0.1)]
    a1_10_08 = [x for x in rows if "A1_thesis" in x["file"] and "2026-10-08" in x["file"]]
    lines = ["# Abort rule for A1 (and the others): evidence from 73 cf5 uSD flights", "",
             "Generated by `experiments/analysis/a1_abort_rule_analysis.py` (2026-10-11). Combined tilt = arccos(cos roll · cos pitch) of the logged stabilizer angles, airborne samples only.", "",
             "## Why the protocol rule does not work for A1",
             f"The protocol rule (|roll| or |pitch| > 25° for 0.5 s) triggers on **{sum(1 for x in a1_10_08 if x['longest_above_25_s'] >= 0.5)} of {len(a1_10_08)}** A1 flights of 2026-10-08, all of which flew to the end: "
             "the geometric controller oscillates in the stacked downwash (±35–40°, ~1.5 Hz, `docs/68`) and recovers. Per flight (longest continuous time above the tilt):", "",
             "| A1 flight 2026-10-08 | max tilt | >25° | >35° | >45° |", "|---|---:|---:|---:|---:|"]
    for x in a1_10_08:
        lines.append(f"| {x['file'].split('thesis')[1][:2]} {x['file'][-12:-4]} | {x['max_tilt_deg']:.0f}° | {x['longest_above_25_s']:.1f} s | {x['longest_above_35_s']:.2f} s | {x['longest_above_45_s']:.2f} s |")
    tum = [x for x in rows if x["class"].startswith("tumble")]
    lines += ["", "## What a tumble looks like", f"{len(tum)} flights tilt beyond 90° (inverted); longest time above 60° per flight: " +
              ", ".join(f"{x['longest_above_60_s']:.2f} s" for x in sorted(tum, key=lambda x: -x['longest_above_60_s'])) + ". "
              "Time from first > 50° to first > 90° (what a human pilot has): " + ", ".join(f"{x['t_50_to_90_s']:.2f} s" for x in tum if x['t_50_to_90_s'] == x['t_50_to_90_s']) + " — "
              "too short for a manual reaction, so the tilt rule is for the automatic advisory flag and for stopping the block, not for the pilot's hand.", "",
             "## Candidate rules: how many flights each triggers (longest continuous time above the tilt ≥ duration)", "",
             "| rule | tumbles (> 90°) | A1 oscillation flights 10-08 | no-tumble flights (≤ 50°, all) |", "|---|---:|---:|---:|"]
    for th, dur in rules:
        a, b = n_trig("tumble", th, dur)
        c = sum(1 for x in a1_10_08 if x[f"longest_above_{th}_s"] >= dur)
        d, e = n_trig("no tumble", th, dur)
        lines.append(f"| tilt > {th}° for {dur} s | {a} / {b} | {c} / {len(a1_10_08)} | {d} / {e} |")
    amb = [x for x in rows if x["class"].startswith("ambiguous")]
    lines += ["", f"{len(amb)} flights peaked between 50° and 90° (10-01 flights, outcome not labelled in the logs): " + ", ".join(f"{x['max_tilt_deg']:.0f}°" for x in amb) + ".", "",
              "## Proposed rule (to be confirmed in the shakedown / with the supervisor)",
              "- **Automatic advisory flag and block stop (all scenarios, A1 included):** combined tilt > 45° for ≥ 0.2 s, or z < 0.25 m, or pose jump. It does not trigger on any A1 oscillation flight of 10-08 and does trigger on the tumbles.",
              "- **Keep the 25° / 0.5 s rule only for scenarios that are calm** (A8, A2–A5, A7 with a stable controller); for A1 with S0/S2/S1/ours it is replaced by the rule above, and the oscillation amplitude itself is a result (roll p99, sd), not an abort reason.",
              "- A tumble is over in < 1 s: the pilot's job is the kill switch / catching the drone, the rule is for classification and for stopping the block after 2 crashes.",
              "- Limits: n = 5 oscillation flights and a handful of tumbles; the 50–90° flights have no outcome label; Omar C has never flown A1, so its A1 behaviour may need another look after the shakedown."]
    (REPO / "docs" / "a1_abort_rule_analysis.md").write_text("\n".join(lines) + "\n")

    fig, ax = plt.subplots(figsize=(8, 5))
    col = {"tumble": "#CC0000", "ambiguous": "#E69F00", "no tumble": "#009E73"}
    for x in rows:
        k = "tumble" if x["class"].startswith("tumble") else ("ambiguous" if x["class"].startswith("ambiguous") else "no tumble")
        isA1 = "A1_thesis" in x["file"] and "2026-10-08" in x["file"]
        ax.scatter(x["max_tilt_deg"], x["longest_above_35_s"] + 0.01, c=col[k], s=70 if isA1 else 25, marker="D" if isA1 else "o", alpha=0.8)
    ax.set_yscale("log"); ax.set_xlabel("max combined tilt of the flight (deg)"); ax.set_ylabel("longest time above 35° (s, +0.01)")
    ax.axvline(45, color="k", ls="--", lw=0.8); ax.text(46, 0.012, "45°", fontsize=8)
    for k, c in col.items(): ax.scatter([], [], c=c, label=k)
    ax.scatter([], [], c="#009E73", marker="D", s=70, label="A1 oscillation flights 10-08")
    ax.legend(fontsize=8); ax.set_title("cf5 uSD flights: oscillation (recovers) vs tumble"); ax.grid(alpha=0.3)
    fig.tight_layout(); fig.savefig(OUT / "fig_abort_rule.png", dpi=150); plt.close(fig)
    print(f"{len(rows)} flights; wrote docs/a1_abort_rule_analysis.md")


if __name__ == "__main__":
    main()
