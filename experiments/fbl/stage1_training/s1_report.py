#!/usr/bin/env python3
"""Summarise a Stage 1 run (loo_results.json) per variant and scenario, compare with the NS2 v2 leave-one-flight-out numbers on the same flights, write report.md + fit_overview.png.
  ~/.pyenv/versions/flying_robots/bin/python experiments/fbl/stage1_training/s1_report.py v0
NS2 comparison is indicative: NS2's R^2 is computed by its own pipeline (gate samples at 100 Hz, its feature set), ours on the FBL region/gate (50 Hz, z component, per flight)."""
import json
import sys
from pathlib import Path
import numpy as np

HERE = Path(__file__).resolve().parent
tag = sys.argv[1] if len(sys.argv) > 1 else "v0"
out = HERE.parent / "out" / "stage1" / tag
res = json.load(open(out / "loo_results.json"))
ns2 = json.load(open(HERE.parents[2] / "experiments/analysis/out/ns2_pilot2_2026-10-17/loo_results.json"))["folds"]
V = res["variants"]; names = list(V)
def col(v, key, sub): return np.array([f[key][sub] for f in V[v].values() if f[key]])
L = [f"# FBL Stage 1 — leave-one-flight-out, tag {tag} (generated by s1_report.py)", "",
     f"{len(V[names[0]])} flights, {res['epochs']} epochs, x/y weight 0.3; baseline removed {np.round(res['baseline'], 3).tolist()} (far-field mean per axis).", "",
     "## Per variant (median over flights; gate = r0 < 0.2 m, neighbour above; z component; R² per flight about the flight's own mean)",
     "| variant | gate R² median | gate R² p25 / p75 | gate % vs zero median | region R² median | flights with gate R² ≥ 0.35 |", "|---|---|---|---|---|---|"]
for v in names:
    g = col(v, "gate_z", "r2"); p = col(v, "gate_z", "pct_vs_zero"); r = col(v, "region_z", "r2")
    L.append(f"| {v} | {np.median(g):.2f} | {np.percentile(g, 25):.2f} / {np.percentile(g, 75):.2f} | {np.median(p):.0f} % | {np.median(r):.2f} | {int((g >= 0.35).sum())} / {len(g)} |")
common = [f for f in V["rom_nn_h9"] if f in ns2 and V["rom_nn_h9"][f]["gate_z"]]
L += ["", f"## Against NS2 v2 on the same {len(common)} flights (indicative)", "| scenario | n | FBL rom_nn_h9 gate R² | FBL rom_only | NS2 v2 R² (its own definition) |", "|---|---|---|---|---|"]
for s in sorted({V["rom_nn_h9"][f]["scenario"] for f in common}):
    fs = [f for f in common if V["rom_nn_h9"][f]["scenario"] == s]
    L.append(f"| {s} | {len(fs)} | {np.median([V['rom_nn_h9'][f]['gate_z']['r2'] for f in fs]):.2f} | {np.median([V['rom_only'][f]['gate_z']['r2'] for f in fs]):.2f} | {np.median([ns2[f]['metrics']['r2'] for f in fs]):.2f} |")
L.append(f"| **all** | {len(common)} | {np.median([V['rom_nn_h9'][f]['gate_z']['r2'] for f in common]):.2f} | {np.median([V['rom_only'][f]['gate_z']['r2'] for f in common]):.2f} | {np.median([ns2[f]['metrics']['r2'] for f in common]):.2f} |")
cd = np.array([f["c_d"] for f in V["rom_only"].values()])
L += ["", f"## Drag coefficient of the ROM-only fit across folds: median {np.median(cd):.3f}, range {cd.min():.3f} – {cd.max():.3f}", "",
      "## All-data fits (in-sample): " + json.dumps(json.load(open(out / "all_data_fit.json")))[:600]]
(out / "report.md").write_text("\n".join(L) + "\n"); print("\n".join(L))
import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
fig, ax = plt.subplots(1, 2, figsize=(12, 4))
ax[0].boxplot([col(v, "gate_z", "r2") for v in names], labels=names, showfliers=False); ax[0].axhline(0.35, color="r", ls=":"); ax[0].set_ylabel("gate R² per held-out flight"); ax[0].set_ylim(-1.5, 1); ax[0].tick_params(axis="x", rotation=20)
x = [V["rom_nn_h9"][f]["gate_z"]["r2"] for f in common]; y = [ns2[f]["metrics"]["r2"] for f in common]
ax[1].scatter(x, y, s=12); ax[1].plot([-1, 1], [-1, 1], "k:"); ax[1].set_xlabel("FBL residual (ROM + net, 9 neurons) gate R²"); ax[1].set_ylabel("NS2 v2 R² (own definition)"); ax[1].set_xlim(-1, 1); ax[1].set_ylim(-1, 1)
fig.tight_layout(); fig.savefig(out / "fit_overview.png", dpi=110)
