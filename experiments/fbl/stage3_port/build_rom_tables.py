#!/usr/bin/env python3
"""Build the ROM lookup table for the FBL onboard port, write npz + C source/header (NOT into the firmware tree), and test it against the bundle.
  ~/.pyenv/versions/flying_robots/bin/python experiments/fbl/stage3_port/build_rom_tables.py --tag v1 [--nz 60 --nr 60]
Outputs in experiments/fbl/out/stage3/rom_table_<tag>/ : rom_table.npz, fbl_rom_table.c/.h, report.md, MODEL_CARD.json. Refuses to overwrite."""
import argparse, hashlib, json, subprocess, sys
from pathlib import Path
import numpy as np
import torch
HERE = Path(__file__).resolve().parent; sys.path.insert(0, str(HERE)); sys.path.insert(0, str(HERE.parent))
import rom_table_lib as L, fbl_rom_runtime as RT  # noqa: E402
from common import bundle as B  # noqa: E402
from common.vehicle import OUR  # noqa: E402

ap = argparse.ArgumentParser(); ap.add_argument("--tag", required=True); ap.add_argument("--nz", type=int, default=60); ap.add_argument("--nr", type=int, default=60)
ap.add_argument("--cd", type=float, default=0.43); a = ap.parse_args()
out = HERE.parent / "out" / "stage3" / f"rom_table_{a.tag}"
if out.exists(): sys.exit(f"{out} exists; choose a new --tag")
out.mkdir(parents=True)
zs, rs, t = L.build(a.nz, a.nr); tab = dict(zs=zs.astype(np.float32), rs=rs.astype(np.float32), t=t.astype(np.float32))
np.savez(out / "rom_table.npz", **tab)

# ---- C source ----
def arr(name, x):
    body = ",\n".join("  " + ", ".join(f"{v:.9e}f" for v in row) for row in x.reshape(-1, 6))
    return f"const float {name}[{x.size}] = {{\n{body}\n}};\n"
h = f"""/* Generated by experiments/fbl/stage3_port/build_rom_tables.py (tag {a.tag}). Do not edit.
 * ROM downwash table of the learned-FBL port: per-unit-C_D acceleration a1(z0, r0) in world z [m/s^2] (negative = pushed down) and its partials
 * d a1/dz0, d a1/dr0, from the authors' analytic ROM on the Crazyflie 2.1 Brushless constants (arm 0.05 m, mass-independent). Layout: [iz][ir][3]. */
#ifndef FBL_ROM_TABLE_H
#define FBL_ROM_TABLE_H
#define FBL_ROM_NZ {a.nz}
#define FBL_ROM_NR {a.nr}
#define FBL_ROM_ZMIN {L.ZMIN}f
#define FBL_ROM_ZMAX {L.ZMAX}f
#define FBL_ROM_RMAX {L.RMAX}f   /* r grid: r = RMAX * (j/(NR-1))^2 */
extern const float fbl_rom_table[FBL_ROM_NZ * FBL_ROM_NR * 3];
#endif
"""
(out / "fbl_rom_table.h").write_text(h)
(out / "fbl_rom_table.c").write_text('#include "fbl_rom_table.h"\n' + arr("fbl_rom_table", tab["t"].astype(np.float32)))

# ---- tests against the bundle (ROM only, same C_D) ----
sys.path.insert(0, str(HERE.parent / "stage2_sim"))
import residual_providers as RP  # noqa: E402
ref = RP.FBLResidual(a.cd, False)
rng = np.random.default_rng(1); n = 3000
res = {"n": n}
errs_a, errs_j, offaxis = [], [], 0.0
for _ in range(n):
    z0 = rng.uniform(0.1, 1.2); r0 = 0.5 * rng.uniform() ** 2; ph = rng.uniform(0, 2 * np.pi)
    ego = np.r_[0, 0, 0.5, rng.uniform(-.5, .5, 3), 0, 0, 0, 1, np.zeros(3)]
    top = np.r_[r0 * np.cos(ph), r0 * np.sin(ph), 0.5 + z0, rng.uniform(-.5, .5, 3), 0, 0, 0, 1, np.zeros(3)]
    acc_r, jerk_r, _ = ref(0.0, ego, top)
    acc, jerk = RT.residual(tab, a.cd, ego[:3], ego[3:6], top[:3], top[3:6])
    offaxis = max(offaxis, abs(acc_r[0]), abs(acc_r[1]))
    errs_a.append(abs(acc[2] - acc_r[2])); errs_j.append(abs(jerk[2] - jerk_r[2]))
ea, ej = np.array(errs_a), np.array(errs_j)
res.update(acc_err_max=float(ea.max()), acc_err_p99=float(np.percentile(ea, 99)), jerk_err_max=float(ej.max()), jerk_err_p99=float(np.percentile(ej, 99)),
           jerk_err_median=float(np.median(ej)), bundle_offaxis_acc_max=float(offaxis))
# jerk consistency by finite differences along a trajectory (top static, ego moving through the jet)
tr = []
for k in range(2000):
    tt = k * 1e-3; p = np.array([-0.3 + 0.3 * tt, 0.02, 0.5]); v = np.array([0.3, 0, 0.0])
    tr.append(RT.residual(tab, a.cd, p, v, np.array([0, 0, 1.0]), np.zeros(3)))
acc_t = np.array([x[0][2] for x in tr]); jerk_t = np.array([x[1][2] for x in tr]); fd = np.gradient(acc_t, 1e-3)
res["jerk_vs_finite_difference_max_abs"] = float(np.abs(fd[5:-5] - jerk_t[5:-5]).max()); res["jerk_peak"] = float(np.abs(jerk_t).max())
# gate / fade continuity
zz = np.linspace(1.0, 1.5, 501); aa = np.array([RT.residual(tab, a.cd, np.zeros(3), np.zeros(3), np.array([0, 0, z]), np.zeros(3))[0][2] for z in zz])
res["fade_max_step_per_cm"] = float(np.abs(np.diff(aa)).max() * 0.01 / 0.001) if False else float(np.abs(np.diff(aa)).max())
res["acc_at_gate_edges"] = {"z0=1.2": float(aa[200]), "z0=1.4": float(aa[400]), "z0=1.5": float(aa[-1])}
rr = np.linspace(0, 0.7, 701); ar = np.array([RT.residual(tab, a.cd, np.array([r, 0, 0.5]), np.zeros(3), np.array([0, 0, 1.0]), np.zeros(3))[0][2] for r in rr])
res["radial_edge_step_at_0.6"] = float(abs(ar[600] - ar[601])); res["acc_at_r0=0.6"] = float(ar[600])
card = dict(tag=a.tag, c_d=a.cd, nz=a.nz, nr=a.nr, zmin=L.ZMIN, zmax=L.ZMAX, rmax=L.RMAX, vehicle=OUR, bundle_sha256=B.bundle_hash(),
            table_sha256=hashlib.sha256((out / "rom_table.npz").read_bytes()).hexdigest(), git_commit=subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip(),
            flash_bytes=a.nz * a.nr * 3 * 4, gate=dict(z_lo=RT.Z_LO, fade=[RT.Z_FADE0, RT.Z_FADE1], r_max=RT.R_MAX_USE), tests=res)
json.dump(card, open(out / "MODEL_CARD.json", "w"), indent=1)
(out / "report.md").write_text(f"""# ROM table {a.tag}: {a.nz} x {a.nr} x 3 floats = {card['flash_bytes']/1024:.1f} KiB flash, C_D {a.cd}
Test against the authors' DownwashResidual (ROM only), {n} random states in z0 0.1-1.2 m, r0 0-0.5 m, random velocities up to 0.5 m/s:
- acceleration z: max error {res['acc_err_max']:.4f}, p99 {res['acc_err_p99']:.4f} m/s^2 (bundle x/y output max {res['bundle_offaxis_acc_max']:.1e}, i.e. force purely along z)
- jerk z: max error {res['jerk_err_max']:.3f}, p99 {res['jerk_err_p99']:.3f}, median {res['jerk_err_median']:.4f} m/s^3
- jerk against finite difference of the table acceleration along a pass: max abs deviation {res['jerk_vs_finite_difference_max_abs']:.3f} (peak jerk {res['jerk_peak']:.2f}) m/s^3
- gate: acceleration at z0 1.2 / 1.4 / 1.5 m = {res['acc_at_gate_edges']}; step at r0 = 0.6 m: {res['radial_edge_step_at_0.6']:.5f} m/s^2 (value {res['acc_at_r0=0.6']:.5f})
""")
print((out / "report.md").read_text())
