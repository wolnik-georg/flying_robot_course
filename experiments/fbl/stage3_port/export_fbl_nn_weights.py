#!/usr/bin/env python3
"""Export the force net (net_f) of a trained ODEFunc checkpoint to the C weights file of the firmware residual (fbl_nn_t fbl_nn_weights, fbl_residual.h).
The C side evaluates exactly the bundle's DownwashResidual network term (Gate 4, stage3_port/c/test_fbl_nn.c). Linking the file enables ctrlFbl.nn_en;
without it the weak symbol is absent and the residual stays ROM only.
  ~/.pyenv/versions/flying_robots/bin/python export_fbl_nn_weights.py <checkpoint.pth> <out.c> [--tag NAME]"""
import argparse, hashlib
from pathlib import Path
import torch

ap = argparse.ArgumentParser(); ap.add_argument("ckpt", type=Path); ap.add_argument("out", type=Path); ap.add_argument("--tag", default=None); a = ap.parse_args()
ck = torch.load(a.ckpt, map_location="cpu", weights_only=False); sd = ck["state_dict"] if "state_dict" in ck else ck
W1, b1, W2, b2 = (sd[k].double() for k in ("net_f.0.weight", "net_f.0.bias", "net_f.2.weight", "net_f.2.bias"))
nh = W1.shape[0]; assert W1.shape == (nh, 2) and W2.shape == (3, nh) and nh <= 16, (W1.shape, W2.shape)
f = lambda x: f"{float(x):.9g}f"
lines = [f"/* Generated by experiments/fbl/stage3_port/export_fbl_nn_weights.py from {a.ckpt.name} (sha256 {hashlib.sha256(a.ckpt.read_bytes()).hexdigest()[:16]})"
         + (f", tag {a.tag}" if a.tag else "") + ". Do not edit. */",
         '#include "fbl_residual.h"', "const fbl_nn_t fbl_nn_weights = {", f"  .nh = {nh},",
         "  .w1 = {" + ", ".join("{" + f(W1[k, 0]) + ", " + f(W1[k, 1]) + "}" for k in range(nh)) + "},",
         "  .b1 = {" + ", ".join(f(x) for x in b1) + "},",
         "  .w2 = {" + ", ".join("{" + ", ".join(f(W2[i, k]) for k in range(nh)) + "}" for i in range(3)) + "},",
         "  .b2 = {" + ", ".join(f(x) for x in b2) + "},", "};"]
a.out.write_text("\n".join(lines) + "\n"); print(f"{a.out}: net_f {nh} neurons")
