def main():
    parser = argparse.ArgumentParser(description="Post-flight trajectory analysis")
    parser.add_argument(
        "--csv", default=None, help="Path to flight CSV (default: latest in logs/)"
    )
    parser.add_argument(
        "--type",
        choices=["circle", "fast_circle", "figure8", "fast_figure8",
                 "autonomous", "flip", "fast_flip", "fast_roll",
                 "helix", "fast_helix", "yaw_spin",
                 "onboard_circle", "onboard_helix", "onboard_figure8"],
        default=None,
        help="Trajectory type (default: inferred from filename)",
    )
    parser.add_argument(
        "--compare",
        default=None,
        metavar="CSV2",
        help="Second CSV to compare against the primary. Generates a side-by-side comparison plot.",
    )
    parser.add_argument(
        "--labels",
        default=None,
        metavar="'A,B'",
        help="Comma-separated labels for the two runs when using --compare (default: filenames).",
    )
    parser.add_argument(
        "--platform-compare",
        choices=["best", "mean"],
        default=None,
        help=(
            "4-way figure-8 comparison across platforms (Standard Geometric / Standard INDI / "
            "Upgraded INDI / Brushless INDI fc_bw=70), same panel types as a single-flight "
            "analysis but side-by-side. 'best' = lowest-RMSE flight per platform, "
            "'mean' = flight closest to that platform's mean RMSE. Ignores --csv/--type/--compare."
        ),
    )
    args = parser.parse_args()

    if args.platform_compare:
        _run_platform_compare(args.platform_compare)
        return

    # Auto-detect CSV
    csv_path = args.csv
    if csv_path is None:
        candidates = sorted(glob.glob("logs/*.csv"))
        if not candidates:
            print("No CSV files found in logs/. Run a flight script first.")
            sys.exit(1)
        csv_path = candidates[-1]
        print(f"Auto-selected: {csv_path}")

    # Infer trajectory type from filename
    traj_type = args.type
    base = os.path.basename(csv_path).lower()
    forced_onboard = None
    if "onboard" in base and "circle" in base:
        forced_onboard = "onboard_circle"
    elif "onboard" in base and "helix" in base:
        forced_onboard = "onboard_helix"
    elif "onboard" in base and ("figure8" in base or "fig8" in base):
        forced_onboard = "onboard_figure8"

    if forced_onboard and traj_type != forced_onboard:
        if args.type is not None:
            print(
                f"Detected onboard log from filename; overriding --type {traj_type} "
                f"with {forced_onboard}."
            )
        traj_type = forced_onboard

    if traj_type is None:
        if "fast_circle" in base:                         # before "circle"
            traj_type = "fast_circle"
        elif "fast_flip" in base:                         # before "flip"
            traj_type = "fast_flip"
        elif "fast_roll" in base:
            traj_type = "fast_roll"
        elif "fast_figure8" in base or "fast_fig8" in base:  # before "figure8"
            traj_type = "fast_figure8"
        elif "fast_helix" in base:                        # before "helix"
            traj_type = "fast_helix"
        elif "onboard" in base and "circle" in base:      # before generic "circle"
            traj_type = "onboard_circle"
        elif "onboard" in base and "helix" in base:       # before generic "helix"
            traj_type = "onboard_helix"
        elif "onboard" in base and ("figure8" in base or "fig8" in base):  # before generic
            traj_type = "onboard_figure8"
        elif "circle" in base:
            traj_type = "circle"
        elif "figure8" in base or "fig8" in base:
            traj_type = "figure8"
        elif "tilted_oval" in base:                       # before generic "oval"
            traj_type = "tilted_oval"
        elif "oval" in base:
            traj_type = "oval"
        elif "corner" in base:
            traj_type = "corner"
        elif "slalom" in base:
            traj_type = "slalom"
        elif "teardrop_wide" in base:                     # before generic "teardrop"
            traj_type = "teardrop_wide"
        elif "teardrop" in base:
            traj_type = "teardrop"
        elif "autonomous" in base:
            traj_type = "autonomous"
        elif "flip" in base:
            traj_type = "flip"
        elif "helix" in base:
            traj_type = "helix"
        elif "yaw_spin" in base:
            traj_type = "yaw_spin"
        elif "hover" in base:
            print("Hover flight — generating RPM balance plot.")
            data, _ = load_csv_with_meta(csv_path)
            plot_rpm_balance(data, csv_path)
            sys.exit(0)
        else:
            print(
                "Cannot infer trajectory type from filename. "
                "Use --type circle|fast_circle|figure8|fast_figure8|autonomous|"
                "flip|fast_flip|fast_roll|helix|fast_helix|yaw_spin"
            )
            sys.exit(1)
        print(f"Inferred trajectory type: {traj_type}")

    data, run_meta = load_csv_with_meta(csv_path)

    if len(data["time_s"]) == 0:
        print("CSV is empty.")
        sys.exit(1)

    print(
        f'Loaded {len(data["time_s"])} rows, t=[{data["time_s"][0]:.2f}, {data["time_s"][-1]:.2f}] s'
    )
    # resolved_poly4d: (segs, speed_scale, xy_scale, loop, label) loaded from the
    # generated Poly4D CSV matching this flight's trajectory/mode/kt, or None.
    resolved_poly4d = None

    if run_meta:
        run_sig = ", ".join(
            f"{k}={v}" for k, v in run_meta.items()
            if k in ("run_trajectory", "run_mode", "run_kt", "run_speed", "run_periodic", "run_reps", "run_att_poly")
        )
        if run_sig:
            print(f"Run signature: {run_sig}")
        meta_traj = run_meta.get("run_trajectory")
        _onboard_types = {"onboard_circle", "onboard_helix", "onboard_figure8"}
        if meta_traj and meta_traj in TRAJECTORIES and traj_type not in _onboard_types:
            if args.type is None and traj_type != meta_traj:
                print(f"Using run signature trajectory: {meta_traj} (instead of filename-inferred {traj_type})")
                traj_type = meta_traj
            elif args.type is not None and traj_type != meta_traj:
                print(
                    f"Warning: --type {traj_type} differs from run signature {meta_traj}. "
                    f"Proceeding with --type."
                )

        # Load the exact Poly4D this flight was generated from (mode + kt bake different durations).
        # Exits with an error if metadata is present but the CSV is missing.
        resolved_poly4d = resolve_poly4d_from_meta(run_meta)

    # Onboard Mode D circle/helix/figure8 — use geometry-based reference
    if traj_type in ("onboard_circle", "onboard_helix", "onboard_figure8"):
        if args.compare:
            print("--compare is not supported for onboard Mode D flights.")
            sys.exit(1)
        import re as _re
        n_reps = int(run_meta.get("run_reps", "0") or "0")
        if n_reps <= 0:
            m = _re.search(r'_r(\d+)_', os.path.basename(csv_path))
            n_reps = int(m.group(1)) if m else 1
        if traj_type == "onboard_circle":
            plot_onboard_circle_analysis(data, csv_path, n_reps=n_reps)
        elif traj_type == "onboard_helix":
            plot_onboard_helix_analysis(data, csv_path, n_reps=n_reps)
        else:
            if resolved_poly4d is not None:
                segs, speed_scale, xy_scale, loop, _, segs8 = resolved_poly4d
            else:
                segs, speed_scale, xy_scale, loop = TRAJECTORIES["figure8"]
                segs8 = None
            analyze_figure8_with_comparison(
                data, csv_path, run_meta, segs, speed_scale, xy_scale, loop,
                also_geom_plot=True, segs8=segs8,
            )
        return

    # Helix: analytic reference ONLY when no matching kt-based Poly4D export exists
    # (legacy fixed-lap_time Mode B flights). When resolved_poly4d is present (our
    # mode1 kt-swept flights), fall through to the same calibrated Poly4D/onboard-8
    # path used for figure8/circle/oval/etc below — the analytic model's hardcoded
    # lap_time (10.5s / 5.25s) does not match the actual kt-dependent flown duration
    # and produces large spurious RMSE from accumulated phase drift.
    if traj_type in ("helix", "fast_helix") and resolved_poly4d is None:
        if args.compare:
            print("--compare is not supported for helix flights.")
            sys.exit(1)
        lap_time = 5.25 if traj_type == "fast_helix" else 10.5
        plot_helix_analysis(data, csv_path, lap_time=lap_time)
        plot_indi_trajectory_panel(data, csv_path)
        plot_rpm_balance(data, csv_path)
        return

    # Yaw spin uses analytic reference, not Poly4D
    if traj_type == "yaw_spin":
        if args.compare:
            print("--compare is not supported for yaw_spin flights.")
            sys.exit(1)
        plot_yaw_spin_analysis(data, csv_path)
        plot_indi_trajectory_panel(data, csv_path)
        plot_rpm_balance(data, csv_path)
        return

    # Flip / fast_flip / fast_roll use angle-tracking analysis, not Poly4D position analysis
    if traj_type in ("flip", "fast_flip", "fast_roll"):
        if args.compare:
            print("--compare is not supported for flip/roll flights.")
            sys.exit(1)
        if traj_type == "fast_flip":
            plot_flip_analysis(data, csv_path,
                               segs=FAST_FLIP_ANGLE_SEGS,
                               t_flip=FAST_FLIP_T_FLIP,
                               height=FAST_FLIP_HEIGHT)
        elif traj_type == "fast_roll":
            # Same angle profile as fast_flip, different axis (roll)
            plot_flip_analysis(data, csv_path,
                               segs=FAST_FLIP_ANGLE_SEGS,
                               t_flip=FAST_FLIP_T_FLIP,
                               height=FAST_FLIP_HEIGHT)
        else:
            plot_flip_analysis(data, csv_path)
        plot_indi_trajectory_panel(data, csv_path)
        plot_rpm_balance(data, csv_path)
        return

    if resolved_poly4d is not None:
        segs, speed_scale, xy_scale, loop, _, segs8 = resolved_poly4d
    else:
        segs, speed_scale, xy_scale, loop = TRAJECTORIES[traj_type]
        segs8 = None

    if traj_type in ("figure8", "fast_figure8") and args.compare:
        print("--compare is not yet supported with unified figure-8 metrics.")
        sys.exit(1)

    # Calibrated Poly4D/onboard-8 path (phase-aligned lap-window RMSE) — used for
    # figure8 always, and for any other type (circle/oval/corner/slalom/tilted_oval/
    # teardrop_wide/helix/...) when a matching onboard degree-8 export (segs8) is
    # available, i.e. every mode1 --onboard flight. Generalized 2026-07-23: this path
    # was previously figure8-only; everything else fell through to plot_analysis()
    # below with NO phase calibration at all (raw absolute CSV time vs reference),
    # which produced spurious 50-100cm "RMSE" on <2m-scale paths from uncorrected
    # takeoff-timing offset. See results_2026-07-15_brushless.md §9.4/§10.
    if not args.compare and (traj_type in ("figure8", "fast_figure8") or segs8 is not None):
        analyze_figure8_with_comparison(
            data, csv_path, run_meta, segs, speed_scale, xy_scale, loop,
            traj_type_label=traj_type, segs8=segs8,
        )
        plot_indi_trajectory_panel(data, csv_path)
        plot_rpm_balance(data, csv_path)
        return

    if args.compare:
        data_b, run_meta_b = load_csv_with_meta(args.compare)
        if len(data_b["time_s"]) == 0:
            print(f"Second CSV is empty: {args.compare}")
            sys.exit(1)
        print(
            f'Loaded {len(data_b["time_s"])} rows from {args.compare}'
        )
        if args.labels:
            parts = args.labels.split(",")
            label_a = parts[0].strip()
            label_b = parts[1].strip() if len(parts) > 1 else os.path.basename(args.compare)
        else:
            label_a = os.path.basename(csv_path).removesuffix(".csv")
            label_b = os.path.basename(args.compare).removesuffix(".csv")
        out_path = os.path.splitext(csv_path)[0] + "_vs_" + os.path.splitext(os.path.basename(args.compare))[0] + ".png"
        base_a = os.path.basename(csv_path).lower()
        _, _, lap_s = infer_figure8_eval_window(base_a, run_meta, segs, speed_scale)
        compare_plot(data, data_b, label_a, label_b,
                     segs, traj_type, speed_scale, xy_scale, loop, out_path,
                     segs8=segs8, duration_s=lap_s,
                     t_min_a=run_meta.get("_phase2_t_start"),
                     t_min_b=run_meta_b.get("_phase2_t_start"))
    else:
        plot_analysis(data, segs, traj_type, speed_scale, xy_scale, loop, csv_path)
        plot_indi_trajectory_panel(data, csv_path)
        plot_rpm_balance(data, csv_path)


if __name__ == "__main__":
    main()
