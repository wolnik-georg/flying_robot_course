def _kt_str(kt):
    """Format kt matching Rust mode_label: strip trailing zeros (0.008000 → '0.008')."""
    return f"{float(kt):.6f}".rstrip("0").rstrip(".")


def poly4d_csv_label(traj, mode, kt, speed):
    """Construct the Poly4D CSV filename label — mirrors export_poly4d.rs::mode_label().

    Mode 0, speed 1.0  →  '{traj}_mode0'
    Mode 0, speed 0.8  →  '{traj}_mode0_speed0.80'
    Mode 1/2/3, kt 0.05 →  '{traj}_mode1_kt0.05'
    """
    mode = int(mode)
    speed = float(speed)
    if mode == 0:
        return f"{traj}_mode0" if abs(speed - 1.0) < 1e-3 \
               else f"{traj}_mode0_speed{speed:.2f}"
    return f"{traj}_mode{mode}_kt{_kt_str(kt)}"


