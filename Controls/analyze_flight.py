def load_poly4d_from_csv(path):
    """Load a Poly4D CSV (CS2 format, 33 cols per row) into a segment list.

    Each segment is a list of 33 floats: [duration, x^0..x^7, y^0..y^7, z^0..z^7, yaw^0..yaw^7].
    This is the same format as the hardcoded *_poly4d lists in this file.
    """
    segs = []
    with open(path, newline="") as f:
        reader = csv.reader(f)
        next(reader)  # skip header line
        for row in reader:
            vals = [v.strip() for v in row if v.strip()]
            if vals:
                segs.append([float(v) for v in vals[:33]])
    return segs


# ── Onboard degree-8 normalized-time polynomial evaluator ────────────────────
# Reads _onboard.csv (cols: duration, cx0..cx8, cy0..cy8 — 19 floats/row).
# The firmware evaluates these at 500 Hz; this reproduces the exact reference.

def load_onboard8_csv(path):
    """Load *_onboard.csv → list of (duration, [cx0..cx8], [cy0..cy8])."""
    segs = []
    with open(path, newline="") as f:
        reader = csv.reader(f)
        next(reader)
        for row in reader:
            vals = [float(v.strip()) for v in row if v.strip()]
            if len(vals) >= 19:
                segs.append((vals[0], vals[1:10], vals[10:19]))
    return segs


def _horner8(c, tau):
    """Evaluate degree-8 polynomial c[0]+c[1]*tau+…+c[8]*tau^8 via Horner."""
    v = c[8]
    for k in range(7, -1, -1):
        v = v * tau + c[k]
    return v


def _horner8_deriv(c, tau):
    """Evaluate first derivative of degree-8 polynomial (normalized time τ)."""
    v = 8.0 * c[8]
    for k in range(7, 0, -1):
        v = v * tau + k * c[k]
    return v


def eval_onboard8_xy(segs, t_global):
    """Evaluate degree-8 onboard poly at t_global [s] → (x, y).
    Rest-to-rest: clamps at both endpoints (no looping).
    """
    total = sum(s[0] for s in segs)
    t = max(0.0, min(float(t_global), total))
    t_acc = 0.0
    seg = segs[-1]
    for s in segs:
        if t <= t_acc + s[0] + 1e-9:
            seg = s
            break
        t_acc += s[0]
    dur, cx, cy = seg
    tau = max(0.0, min((t - t_acc) / dur, 1.0)) if dur > 0 else 0.0
    return _horner8(cx, tau), _horner8(cy, tau)


def eval_onboard8_vel(segs, t_global):
    """First derivative of onboard poly → (vx, vy) in physical units."""
    total = sum(s[0] for s in segs)
    t = max(0.0, min(float(t_global), total))
    t_acc = 0.0
    seg = segs[-1]
    for s in segs:
        if t <= t_acc + s[0] + 1e-9:
            seg = s
            break
        t_acc += s[0]
    dur, cx, cy = seg
    tau = max(0.0, min((t - t_acc) / dur, 1.0)) if dur > 0 else 0.0
    inv_dur = 1.0 / dur if dur > 0 else 0.0
    return _horner8_deriv(cx, tau) * inv_dur, _horner8_deriv(cy, tau) * inv_dur


def _horner8_deriv2(c, tau):
    """Evaluate second derivative of degree-8 polynomial wrt normalized time tau."""
    v = 8.0 * 7.0 * c[8]
    for k in range(7, 1, -1):
        v = v * tau + k * (k - 1) * c[k]
    return v


def compute_planned_attitude_8(segs8, t_global):
    """Compute planned roll/pitch/yaw from differential flatness of onboard degree-8 poly.

    segs8: list of (duration, [cx0..cx8], [cy0..cy8]) in normalized time tau.
    Returns (roll_deg, pitch_deg, yaw_deg).  Z is assumed flat (az=0).
    """
    total = sum(s[0] for s in segs8)
    t = max(0.0, min(float(t_global), total))
    t_acc = 0.0
    seg = segs8[-1]
    for s in segs8:
        if t <= t_acc + s[0] + 1e-9:
            seg = s
            break
        t_acc += s[0]
    dur, cx, cy = seg
    tau = max(0.0, min((t - t_acc) / dur, 1.0)) if dur > 0 else 0.0
    inv_dur2 = (1.0 / dur) ** 2 if dur > 0 else 0.0
    ax = _horner8_deriv2(cx, tau) * inv_dur2
    ay = _horner8_deriv2(cy, tau) * inv_dur2
    az = 0.0  # flat trajectory
    f = np.array([ax, ay, az + GRAVITY])
    f_norm = np.linalg.norm(f)
    if f_norm < 1e-9:
        return 0.0, 0.0, 0.0
    zb = f / f_norm
    xc = np.array([1.0, 0.0, 0.0])  # yaw_d = 0 for figure-8
    zcxc = np.cross(zb, xc)
    zcxc_n = np.linalg.norm(zcxc)
    yb = zcxc / zcxc_n if zcxc_n > 1e-9 else np.array([0.0, 1.0, 0.0])
    xb = np.cross(yb, zb)
    R = np.column_stack([xb, yb, zb])
    roll_rad = np.arctan2(R[2, 1], R[2, 2])
    pitch_rad = -np.arcsin(-float(np.clip(R[2, 0], -1.0, 1.0)))
    yaw_rad = np.arctan2(R[1, 0], R[0, 0])
    return np.degrees(roll_rad), np.degrees(pitch_rad), np.degrees(yaw_rad)


