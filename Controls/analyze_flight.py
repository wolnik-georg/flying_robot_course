def load_csv_with_meta(path):
    meta = {}
    rows = {
        c: []
        for c in [
            "time_s",
            "x", "y", "z",
            "vx", "vy", "vz",
            "roll_deg", "pitch_deg", "yaw_deg",
            "thrust",
            "vbat",                          # battery voltage [V]
            "gyro_x", "gyro_y", "gyro_z",   # deg/s — body angular velocity
            "acc_x", "acc_y", "acc_z",       # g — body accelerometer
            "rpm_m1", "rpm_m2", "rpm_m3", "rpm_m4",          # RPM deck (NaN if not fitted)
            "tau_x", "tau_y", "tau_z",                        # INDI torque commands [N·m]
            "alp_x", "alp_y", "alp_z",                       # filtered angular accel [rad/s²]
            "alp_raw_x", "alp_raw_y", "alp_raw_z",           # pre-filter angular accel [rad/s²]
        ]
    }
    with open(path) as f:
        data_lines = []
        for line in f:
            if line.startswith("#"):
                line_s = line.strip()
                if line_s.startswith("# meta:") and "=" in line_s:
                    kv = line_s[len("# meta:"):]
                    key, value = kv.split("=", 1)
                    meta[key.strip()] = value.strip()
                continue
            data_lines.append(line)
        reader = csv.DictReader(io.StringIO("".join(data_lines)))
        for row in reader:
            for k in rows:
                try:
                    rows[k].append(float(row[k]))
                except (KeyError, ValueError):
                    rows[k].append(float("nan"))
    data = {k: np.array(v) for k, v in rows.items()}
    # CS2 flight.py logs two phases (takeoff then trajectory) in one CSV, each with its
    # own timer that resets to ~0 at the phase boundary.  Detect the first backward jump
    # and add the end-of-previous-phase time to all subsequent timestamps so the full
    # recording has a single monotone time axis.  Without this, any time-based window
    # (times >= phase_t_start) selects data from BOTH phases, causing duplicate lines.
    ts = data["time_s"]
    for i in range(1, len(ts)):
        if ts[i] < ts[i - 1]:
            # Store the phase-2 start time so callers can restrict searches to the
            # trajectory phase and avoid false detections in the takeoff phase.
            meta["_phase2_t_start"] = float(ts[i - 1])
            ts[i:] += ts[i - 1]
            break  # CS2 produces at most one phase reset per log
    return data, meta


# ── Metrics ─────────────────────────────────────────────────────────────────

def compute_metrics(data, plan, plan_vel, planned_att_arr):
    """Return a dict of tracking quality metrics.

    Z error uses relative coordinates (poly4d is relative_position=True):
    err_z = |(z_actual − z_start) − pz_planned|
    """
    px, py, pz_rel = plan[:, 0], plan[:, 1], plan[:, 2]
    z0 = data["z"][0]
    err_xy = np.sqrt((data["x"] - px) ** 2 + (data["y"] - py) ** 2)
    err_z  = np.abs((data["z"] - z0) - pz_rel)
    err_3d = np.sqrt(err_xy ** 2 + err_z ** 2)

    er = data["roll_deg"]  - planned_att_arr[:, 0]
    ep = data["pitch_deg"] - planned_att_arr[:, 1]

    ex = data["x"] - px
    with np.errstate(invalid="ignore"):
        lag_corr = float(np.corrcoef(ex, data["vx"])[0, 1])

    speed_actual  = np.sqrt(data["vx"]**2 + data["vy"]**2 + data["vz"]**2)
    speed_planned = np.sqrt(plan_vel[:, 0]**2 + plan_vel[:, 1]**2 + plan_vel[:, 2]**2)
    speed_err = speed_actual - speed_planned

    vbat = data.get("vbat", np.array([np.nan]))
    vbat_min = float(np.nanmin(vbat)) if not np.all(np.isnan(vbat)) else float("nan")

    return {
        "xy_rms":        float(np.sqrt(np.nanmean(err_xy ** 2))),
        "xy_max":        float(np.nanmax(err_xy)),
        "z_rms":         float(np.sqrt(np.nanmean(err_z ** 2))),
        "3d_rms":        float(np.sqrt(np.nanmean(err_3d ** 2))),
        "roll_err_rms":  float(np.sqrt(np.nanmean(er ** 2))),
        "pitch_err_rms": float(np.sqrt(np.nanmean(ep ** 2))),
        "lag_corr":      lag_corr,
        "speed_rms":     float(np.sqrt(np.nanmean(speed_err ** 2))),
        "speed_max_actual": float(np.nanmax(speed_actual)),
        "thrust_mean":   float(np.nanmean(data["thrust"])),
        "thrust_max":    float(np.nanmax(data["thrust"])),
        "vbat_min":      vbat_min,
        "err_xy":        err_xy,
        "err_z":         err_z,
        "err_3d":        err_3d,
        "roll_err":      er,
        "pitch_err":     ep,
        "speed_actual":  speed_actual,
        "speed_planned": speed_planned,
    }


