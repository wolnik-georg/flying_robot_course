def resolve_poly4d_from_meta(run_meta):
    """Load the correct Poly4D for a flight given its metadata dict.

    Returns (segs, speed_scale, xy_scale, loop, label) when metadata is present,
    or None when metadata has no run_trajectory (old logs without metadata).

    Raises SystemExit if metadata is present but the CSV is missing — this prevents
    silently comparing against the wrong planned trajectory.
    """
    traj  = run_meta.get("run_trajectory", "")
    mode  = run_meta.get("run_mode", "0")
    kt    = run_meta.get("run_kt", "0.008")
    speed = run_meta.get("run_speed", "1.0")

    if not traj:
        return None

    label = poly4d_csv_label(traj, mode, kt, speed)
    path  = find_poly4d_csv(label)

    if path is None:
        kt_arg    = f" --kt {kt}"       if int(mode) != 0               else ""
        speed_arg = f" --speed {speed}" if abs(float(speed) - 1.0) > 1e-3 else ""
        print(f"  Error: Poly4D CSV '{label}.csv' not found in {POLY4D_CSV_DIR}")
        print(f"  Generate it first with:")
        print(f"    cd flying_drone_stack && cargo run --release --bin export_poly4d "
              f"-- --trajectory {traj} --mode {mode}{kt_arg}{speed_arg}")
        print(f"  Or run:  bash Controls/pregenerate_poly4d.sh")
        sys.exit(1)

    segs    = load_poly4d_from_csv(path)
    is_loop = (traj == "circle")
    lap_s   = sum(s[0] for s in segs)
    print(f"  Poly4D  : {label}  ({len(segs)} segs, lap={lap_s:.3f}s)")

    # Also load the onboard degree-8 CSV when available (more accurate reference).
    ob8_path = find_onboard8_csv(label)
    segs8 = load_onboard8_csv(ob8_path) if ob8_path else None
    if segs8:
        print(f"  Onboard8: {label}_onboard.csv  ({len(segs8)} segs) — used as primary reference")

    return segs, 1.0, 1.0, is_loop, label, segs8


def infer_figure8_eval_window(base, run_meta, segs, speed_scale):
    """Lap window [s] for metrics: metadata, else filename (onboard_m0_s1-0x_r1, …)."""
    import re

    n_reps = int(run_meta.get("run_reps", "0") or "0")
    if n_reps <= 0:
        m = re.search(r"_r(\d+)_", base)
        n_reps = int(m.group(1)) if m else 1

    lap_s = run_meta.get("run_lap_time_s")
    if lap_s:
        lap_s = float(lap_s)
    else:
        speed_mult = float(run_meta.get("run_speed", "0") or "0")
        if speed_mult <= 0:
            m = re.search(r"_s(\d+)-0x", base) or re.search(r"_s([\d.]+)x", base)
            speed_mult = float(m.group(1)) if m else 1.0
        nominal_lap = sum(float(s[0]) for s in segs) / max(speed_scale, 1e-6)
        lap_s = nominal_lap / max(speed_mult, 1e-6)

    eval_window = lap_s * max(n_reps, 1)
    return eval_window, n_reps, lap_s


def find_figure8_traj_start(data, speed_threshold=0.12, z_min=0.5, t_min=None):
    """First time HORIZONTAL speed exceeds threshold at flight altitude.

    Uses only vx/vy (not vz) so the vertical takeoff climb — where vz easily
    exceeds the threshold while the drone is still centimetres off the ground —
    does not produce a false early detection.  The z_min gate provides a second
    guard: we only look for horizontal motion once the drone is airborne.

    t_min: if provided (the phase-2 start time from load_csv_with_meta), restrict
    the search to rows after the takeoff/trajectory phase boundary so that
    horizontal motion during the takeoff phase does not produce a false detection.
    """
    speed_h = np.sqrt(data["vx"] ** 2 + data["vy"] ** 2)
    z = data["z"]
    times = data["time_s"]
    # Only search within the trajectory phase (after the takeoff phase boundary).
    phase2 = (times >= t_min) if t_min is not None else np.ones(len(times), dtype=bool)
    moving = phase2 & (speed_h > speed_threshold) & (z > z_min)
    if not np.any(moving):
        moving = phase2 & (speed_h > speed_threshold)
        if not np.any(moving):
            # No motion detected in phase 2 at all — return start of phase 2.
            idx = int(np.argmax(phase2)) if np.any(phase2) else 0
            return float(times[idx])
    return float(times[int(np.argmax(moving))])


def _figure8_lap_mask(times, t_start, duration_s):
    return (times >= t_start) & (times <= t_start + duration_s + 1e-6)


def compute_figure8_geom_metrics(data, t_start=None, duration_s=None, segs8=None):
    """Nearest-point distance to planned path (time-invariant shape error).

    If segs8 (onboard degree-8 segments) is provided, the reference is the actual
    planned polynomial curve sampled at 500 Hz.  Otherwise falls back to the
    coarse 10-waypoint linear polyline (mode-0 only).
    """
    ts = data["time_s"]
    mask = np.isfinite(ts)
    if t_start is not None and duration_s is not None:
        mask = mask & _figure8_lap_mask(ts, t_start, duration_s)
    xa = data["x"][mask]
    ya = data["y"][mask]
    za = data["z"][mask]
    x0, y0, z0 = float(xa[0]), float(ya[0]), float(za[0])

    if segs8 is not None:
        # Dense polynomial reference — offset by measured start position.
        total_dur = sum(s[0] for s in segs8)
        n_pts = max(500, int(total_dur * 500))
        t_pts = np.linspace(0.0, total_dur, n_pts)
        xy_pts = np.array([eval_onboard8_xy(segs8, t) for t in t_pts])
        # Offset: align polynomial origin (t=0) to first flight point.
        ref_x0, ref_y0 = eval_onboard8_xy(segs8, 0.0)
        ref_dense = np.column_stack([
            xy_pts[:, 0] - ref_x0 + x0,
            xy_pts[:, 1] - ref_y0 + y0,
            np.full(n_pts, z0),
        ])
    else:
        # Fallback: coarse waypoint polyline (mode-0 only).
        ref_wps = FIGURE8_WAYPOINTS_XY.copy()
        ref_wps[:, 0] += x0
        ref_wps[:, 1] += y0
        dense = []
        for i in range(len(ref_wps) - 1):
            a = np.append(ref_wps[i], z0)
            b = np.append(ref_wps[i + 1], z0)
            for s in np.linspace(0.0, 1.0, 60, endpoint=False):
                dense.append((1.0 - s) * a + s * b)
        dense.append(np.array([ref_wps[-1, 0], ref_wps[-1, 1], z0]))
        ref_dense = np.asarray(dense)

    err_xy = np.zeros(xa.shape)
    err_3d = np.zeros(xa.shape)
    for i in range(len(xa)):
        dx = ref_dense[:, 0] - xa[i]
        dy = ref_dense[:, 1] - ya[i]
        dz = ref_dense[:, 2] - za[i]
        dxy2 = dx * dx + dy * dy
        j = int(np.argmin(dxy2))
        err_xy[i] = np.sqrt(dxy2[j])
        err_3d[i] = np.sqrt(dxy2[j] + dz[j] * dz[j])

    return {
        "xy_rms": float(np.sqrt(np.nanmean(err_xy ** 2))),
        "3d_rms": float(np.sqrt(np.nanmean(err_3d ** 2))),
        "xy_max": float(np.nanmax(err_xy)),
    }


def poly4d_metrics_over_window(
    data, segs, speed_scale, xy_scale, loop,
    t_start, duration_s, time_shift=0.0,
):
    """Poly4D tracking metrics on [t_start, t_start + duration_s] with phase alignment."""
    times = data["time_s"]
    mask = _figure8_lap_mask(times, t_start, duration_s)
    if not np.any(mask):
        mask = np.ones(len(times), dtype=bool)
        t_start = float(times[0])
    t_rel = times[mask] - t_start
    plan = np.array([
        eval_poly4d(segs, max(0.0, tr + time_shift), speed_scale, xy_scale, loop)
        for tr in t_rel
    ])
    plan_vel = np.array([
        eval_poly4d_vel(segs, max(0.0, tr + time_shift), speed_scale, xy_scale, loop)
        for tr in t_rel
    ])
    planned_att = np.array([
        compute_planned_attitude(segs, max(0.0, tr + time_shift), speed_scale, xy_scale, loop)
        for tr in t_rel
    ])
    sub = {k: data[k][mask] for k in data}
    return compute_metrics(sub, plan, plan_vel, planned_att)


def onboard8_metrics_over_window(data, segs8, t_start, duration_s, time_shift=0.0):
    """Tracking metrics against degree-8 onboard polynomial reference.

    Evaluates segs8 at each flight timestamp, applying time_shift (phase alignment).
    Rest-to-rest: clamps at endpoints — no looping.
    Returns dict with xy_rms, 3d_rms, xy_max, lag_corr.
    """
    times = data["time_s"]
    mask = _figure8_lap_mask(times, t_start, duration_s)
    if not np.any(mask):
        mask = np.ones(len(times), dtype=bool)
        t_start = float(times[0])
    t_rel = times[mask] - t_start

    # Evaluate reference at each flight timestamp; offset origin to flight start.
    x0_ref, y0_ref = eval_onboard8_xy(segs8, 0.0)
    x0_flight, y0_flight = float(data["x"][mask][0]), float(data["y"][mask][0])
    dx_off = x0_flight - x0_ref
    dy_off = y0_flight - y0_ref

    ref_xy = np.array([eval_onboard8_xy(segs8, max(0.0, tr + time_shift)) for tr in t_rel])
    ref_x = ref_xy[:, 0] + dx_off
    ref_y = ref_xy[:, 1] + dy_off

    xa, ya, za = data["x"][mask], data["y"][mask], data["z"][mask]
    z_ref = float(np.nanmean(za))  # z is constant for flat figure-8
    ex = xa - ref_x
    ey = ya - ref_y
    ez = za - z_ref

    err_xy = np.sqrt(ex ** 2 + ey ** 2)
    err_3d = np.sqrt(ex ** 2 + ey ** 2 + ez ** 2)

    # Lag correlation (positive = drone lags reference)
    ref_speed = np.array([np.sqrt(sum(v**2 for v in eval_onboard8_vel(segs8, max(0.0, tr)))) for tr in t_rel])
    flight_speed = np.sqrt(data["vx"][mask]**2 + data["vy"][mask]**2)
    if ref_speed.std() > 1e-6 and flight_speed.std() > 1e-6:
        corr = np.correlate(flight_speed - flight_speed.mean(), ref_speed - ref_speed.mean(), mode="full")
        lag_corr = float(corr[len(corr) // 2] / (np.sqrt(np.sum((flight_speed - flight_speed.mean())**2) * np.sum((ref_speed - ref_speed.mean())**2)) + 1e-12))
    else:
        lag_corr = 0.0

    planned_att = np.array([
        compute_planned_attitude_8(segs8, max(0.0, tr + time_shift)) for tr in t_rel
    ])
    roll_a  = data["roll_deg"][mask]  if "roll_deg"  in data else np.zeros(int(np.sum(mask)))
    pitch_a = data["pitch_deg"][mask] if "pitch_deg" in data else np.zeros(int(np.sum(mask)))
    roll_err_rms  = float(np.sqrt(np.nanmean((roll_a  - planned_att[:, 0]) ** 2)))
    pitch_err_rms = float(np.sqrt(np.nanmean((pitch_a - planned_att[:, 1]) ** 2)))

    return {
        "xy_rms":        float(np.sqrt(np.nanmean(err_xy ** 2))),
        "3d_rms":        float(np.sqrt(np.nanmean(err_3d ** 2))),
        "xy_max":        float(np.nanmax(err_xy)),
        "lag_corr":      lag_corr,
        "roll_err_rms":  roll_err_rms,
        "pitch_err_rms": pitch_err_rms,
    }


def calibrate_onboard8_phase(data, segs8, t_start, duration_s):
    """Find best time_shift for onboard-8 reference (no speed_scale — timing is fixed)."""
    times = data["time_s"]
    mask = _figure8_lap_mask(times, t_start, duration_s)
    if int(np.sum(mask)) < 10:
        return 0.0
    t_rel = times[mask] - t_start
    xa, ya = data["x"][mask], data["y"][mask]
    x0_ref, y0_ref = eval_onboard8_xy(segs8, 0.0)
    dx_off = float(xa[0]) - x0_ref
    dy_off = float(ya[0]) - y0_ref
    # Search range widened 2026-07-23: +-0.5s was clipping (best_dt landing exactly on the
    # boundary) for some flights (helix, both platforms — genuine, resolved by widening).
    # +-0.75s at the same resolution (10ms). NOT widened further: one flight (tilted_oval
    # upgraded, 2026-07-23) still clips at +-1.5s too — that is a real per-flight anomaly, not
    # a search-window artifact (a "phase shift" beyond ~1s stops being a believable constant
    # startup-latency correction). See results_2026-07-15_brushless.md §9.7.
    best_rms, best_dt = float("inf"), 0.0
    for dt in np.linspace(-0.75, 0.75, 151):
        ref_xy = np.array([eval_onboard8_xy(segs8, max(0.0, tr + dt)) for tr in t_rel])
        ex = xa - (ref_xy[:, 0] + dx_off)
        ey = ya - (ref_xy[:, 1] + dy_off)
        rms = float(np.sqrt(np.nanmean(ex**2 + ey**2)))
        if rms < best_rms:
            best_rms, best_dt = rms, float(dt)
    return best_dt


