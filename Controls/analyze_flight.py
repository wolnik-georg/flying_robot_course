def calibrate_poly4d_phase(data, segs, speed_scale, xy_scale, loop, t_start, duration_s):
    """Fit speed_scale and time_shift on the lap window (same treatment for every log).

    speed_scale: stretch/compress planned phase vs wall clock.
    time_shift: constant offset (s) on time relative to motion start.
    """
    times = data["time_s"]
    mask = _figure8_lap_mask(times, t_start, duration_s)
    if int(np.sum(mask)) < 10:
        return speed_scale, 0.0
    t_rel = times[mask] - t_start
    xa, ya = data["x"][mask], data["y"][mask]
    best_rms, best_ss, best_dt = float("inf"), speed_scale, 0.0
    for ss in np.linspace(max(0.5, speed_scale * 0.88), min(1.5, speed_scale * 1.12), 41):
        for dt in np.linspace(-0.75, 0.75, 151):
            plan = np.array([
                eval_poly4d(segs, max(0.0, tr + dt), ss, xy_scale, loop) for tr in t_rel
            ])
            err_xy = np.sqrt((xa - plan[:, 0]) ** 2 + (ya - plan[:, 1]) ** 2)
            rms = float(np.sqrt(np.nanmean(err_xy ** 2)))
            if rms < best_rms:
                best_rms, best_ss, best_dt = rms, float(ss), float(dt)
    return best_ss, best_dt


def calibrate_poly4d_speed_scale(data, segs, speed_scale, xy_scale, loop, eval_window_s):
    """Legacy 1D timing fit (speed_scale only, window from t=0)."""
    ss, _ = calibrate_poly4d_phase(
        data, segs, speed_scale, xy_scale, loop, 0.0, eval_window_s
    )
    return ss


