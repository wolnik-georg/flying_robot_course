# ---------------------------------------------------------------------------
# Flight function
# ---------------------------------------------------------------------------


def fly_fast_circle(scf, n_laps):
    cf = scf.cf
    hl = cf.high_level_commander
    traj_id = 1

    print(f"\nUploading fast circle trajectory ({len(circle_poly4d)} segments)...")
    duration = upload_trajectory(cf, traj_id, circle_poly4d, scale=SCALE)
    actual_s = duration / SPEED_SCALE
    print(f"  Planned: {duration:.2f} s  |  at SPEED_SCALE={SPEED_SCALE}: {actual_s:.1f} s/lap")
    print(f"  {n_laps} lap(s): {actual_s * n_laps:.1f} s total")
    print(f"  WARNING: 2× speed → ~4× centripetal acceleration. Stay clear.")

    print("Resetting Kalman estimator...")
    reset_kalman(cf)
    wait_for_kalman(scf)

    cf.platform.send_arming_request(True)
    time.sleep(1.0)

    cf.param.set_value("stabilizer.controller", "6")
    time.sleep(0.1)

    log_cfg = start_live_log(cf)
    logger = FlightLogger(cf, name="fast_circle")
    logger.start()

    print(f"\nTakeoff to {HOVER_HEIGHT:.2f} m over 2 s...")
    hl.takeoff(HOVER_HEIGHT, 2.0)
    print("  Waiting 3 s for climb + estimator stabilization...")
    time.sleep(3.0)

    print("\nOOT Rust geometric controller active. Stabilizing hover for 2.5 s...")
    time.sleep(2.5)

    for lap in range(1, n_laps + 1):
        print(f"\n--- Lap {lap}/{n_laps}: starting fast circle ---")
        print(f"  Duration: {actual_s:.1f} s at SPEED_SCALE={SPEED_SCALE}")
        if lap == 1:
            logger.mark_traj_start()
        hl.start_trajectory(traj_id, 1.0 / SPEED_SCALE, relative_position=True)
        time.sleep(max(0.5, actual_s - 0.05))

    print("\nLanding...")
    logger.stop()
    log_cfg.stop()
    hl.land(0.0, 2.0)
    time.sleep(2.0)
    hl.stop()
    print("Done.")


