if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Fast circle flight via HLC (2× speed)")
    parser.add_argument("--laps", type=int, default=DEFAULT_LAPS,
                        help=f"Number of laps (default: {DEFAULT_LAPS})")
    parser.add_argument("--uri", default=None,
                        help="Crazyflie URI (default: radio://0/80/2M/E7E7E7E7E7)")
    args = parser.parse_args()

    uri = args.uri or uri_helper.uri_from_env(default=DEFAULT_URI)
    print(f"Connecting to {uri}...")
    print(f"Laps: {args.laps}  |  SPEED_SCALE: {SPEED_SCALE}  |  ~{TRAJ_PLANNED_DURATION/SPEED_SCALE:.1f} s/lap")

    cflib.crtp.init_drivers()
    with SyncCrazyflie(uri, cf=Crazyflie(rw_cache="./cache")) as scf:
        fly_fast_circle(scf, n_laps=args.laps)
