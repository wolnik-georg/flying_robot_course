# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def upload_trajectory(cf, traj_id, trajectory):
    traj_mem = cf.mem.get_mems(MemoryElement.TYPE_TRAJ)[0]
    traj_mem.trajectory = []
    total = 0.0
    for row in trajectory:
        dur = row[0]
        traj_mem.trajectory.append(
            Poly4D(
                dur,
                Poly4D.Poly(row[1:9]),    # x coefficients
                Poly4D.Poly(row[9:17]),   # y coefficients
                Poly4D.Poly(row[17:25]),  # z coefficients (constant altitude)
                Poly4D.Poly(row[25:33]),  # yaw coefficients (constant heading)
            )
        )
        total += dur
    ok = traj_mem.write_data_sync()
    if not ok:
        raise RuntimeError("Trajectory upload failed")
    cf.high_level_commander.define_trajectory(traj_id, 0, len(traj_mem.trajectory))
    return total


def wait_for_kalman(scf, threshold=KALMAN_THRESH):
    print("  Waiting for Kalman estimator to converge...")
    log_cfg = LogConfig(name="KalmanVar", period_in_ms=200)
    log_cfg.add_variable("kalman.varPX", "float")
    log_cfg.add_variable("kalman.varPY", "float")
    log_cfg.add_variable("kalman.varPZ", "float")
    hist_x = [1e3] * 10
    hist_y = [1e3] * 10
    hist_z = [1e3] * 10
    with SyncLogger(scf, log_cfg) as logger:
        for entry in logger:
            d = entry[1]
            hist_x.append(d["kalman.varPX"]); hist_x.pop(0)
            hist_y.append(d["kalman.varPY"]); hist_y.pop(0)
            hist_z.append(d["kalman.varPZ"]); hist_z.pop(0)
            sx = max(hist_x) - min(hist_x)
            sy = max(hist_y) - min(hist_y)
            sz = max(hist_z) - min(hist_z)
            print(f"    spread: x={sx:.5f}  y={sy:.5f}  z={sz:.5f}", end="\r")
            if sx < threshold and sy < threshold and sz < threshold:
                print(f"\n  Converged (spread < {threshold}).")
                return
    print("\n  Warning: Kalman did not converge within log window.")


# ---------------------------------------------------------------------------
# Main flight
# ---------------------------------------------------------------------------

def fly_circle(scf, n_laps, controller):
    cf = scf.cf
    hl = cf.high_level_commander
    traj_id = 1

    # Upload before takeoff so it's ready
    print(f"\nUploading circle trajectory ({len(circle_poly4d)} segments)...")
    duration = upload_trajectory(cf, traj_id, circle_poly4d)
    actual_s = duration / SPEED_SCALE
    print(f"  Planned duration: {duration:.2f} s  |  at SPEED_SCALE={SPEED_SCALE}: {actual_s:.1f} s per lap")
    print(f"  {n_laps} lap(s): {actual_s * n_laps:.1f} s total flight")

    # Set controller
    ctrl_names = {2: "Mellinger (firmware)", 6: "OOT Rust geometric"}
    print(f"\nSetting controller: {ctrl_names.get(controller, str(controller))} (type {controller})")
    cf.param.set_value("stabilizer.controller", str(controller))
    time.sleep(0.2)

    # Reset Kalman estimator
    print("Resetting Kalman estimator...")
    cf.param.set_value("kalman.resetEstimation", "1")
    time.sleep(0.1)
    cf.param.set_value("kalman.resetEstimation", "0")

    wait_for_kalman(scf)

    # Takeoff
    print(f"\nTakeoff to {HOVER_HEIGHT:.2f} m over 4 s...")
    hl.takeoff(HOVER_HEIGHT, 4.0)
    print("  Waiting 8 s for climb + estimator stabilization...")
    time.sleep(8.0)

    # Read EKF position to confirm we're hovering
    pos_cfg = LogConfig(name="Pos", period_in_ms=100)
    pos_cfg.add_variable("stateEstimate.x", "float")
    pos_cfg.add_variable("stateEstimate.y", "float")
    pos_cfg.add_variable("stateEstimate.z", "float")
    with SyncLogger(scf, pos_cfg) as logger:
        for entry in logger:
            d = entry[1]
            x, y, z = d["stateEstimate.x"], d["stateEstimate.y"], d["stateEstimate.z"]
            print(f"  Hover position: x={x:+.3f}  y={y:+.3f}  z={z:.3f} m")
            break

    # Execute trajectory (n_laps times; each lap starts from current position)
    for lap in range(1, n_laps + 1):
        print(f"\n--- Lap {lap}/{n_laps}: starting trajectory ---")
        print(f"  Duration: {actual_s:.1f} s at SPEED_SCALE={SPEED_SCALE}")
        hl.start_trajectory(traj_id, SPEED_SCALE, relative_position=True)

        # Log position during flight
        t_end = time.time() + actual_s + 1.5
        with SyncLogger(scf, pos_cfg) as logger:
            for entry in logger:
                d = entry[1]
                x, y, z = d["stateEstimate.x"], d["stateEstimate.y"], d["stateEstimate.z"]
                print(f"  lap {lap}  x={x:+.3f}  y={y:+.3f}  z={z:.3f}          ", end="\r")
                if time.time() >= t_end:
                    break
        print()

        # Small pause between laps
        if lap < n_laps:
            print("  Hovering 2 s between laps...")
            hl.go_to(0.0, 0.0, HOVER_HEIGHT, 0.0, 2.0, relative=True)
            time.sleep(2.5)

    # Land
    print("\nLanding...")
    hl.land(0.0, 3.0)
    time.sleep(4.0)
    hl.stop()
    print("Done.")


