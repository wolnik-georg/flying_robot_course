#!/usr/bin/env python3
"""
Spline Circle Flight — min-snap trajectory via Crazyflie high-level commander
=============================================================================
Uploads a minimum-snap circle trajectory (computed by our Rust planner) to
the drone's onboard trajectory memory and executes it using the high-level
commander.  The drone's onboard polynomial evaluator runs at ~100 Hz, so the
controller receives full position + velocity + acceleration — no radio timing
constraints.

Usage:
    ~/.pyenv/versions/flying_robots/bin/python run_spline_circle.py
    ~/.pyenv/versions/flying_robots/bin/python run_spline_circle.py --controller 6
    ~/.pyenv/versions/flying_robots/bin/python run_spline_circle.py --laps 2

The --controller flag selects:
    6  OOT Rust geometric controller (default — requires updated firmware)
    2  Mellinger firmware controller  (fallback)
"""

